import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { daemonState } from "./daemon.mjs";
import { DAEMON_NODE_ARGS } from "./launch.mjs";
import { pathKey } from "./paths.mjs";
import { importLegacyIntake } from "./reports/intake.mjs";
import { atomicWriteFile, atomicWriteJson, ensureDir, readJsonSafe, readTextSafe, removeSafe } from "./util/fsx.mjs";
import { VERSION } from "./version.mjs";

export const RUN_KEY = "HKCU\\Software\\Microsoft\\Windows\\CurrentVersion\\Run";
export const RUN_VALUE = "omo-health";
export const STUB_NAME = "omo-health-sensor.ts";
export function runValueName(env = process.env) {
	return env.OMO_HEALTH_RUN_VALUE || RUN_VALUE;
}

export function defaultRegRunner(args) {
	const result = spawnSync("reg.exe", args, { windowsHide: true, encoding: "utf8", timeout: 15_000 });
	return { status: result.status, stdout: result.stdout ?? "", stderr: result.stderr ?? "" };
}

/** Files a loaded sensor runs; the same list as SENSOR_FILES in bootstrap/boot.mjs. */
const SENSOR_FILES = ["extension/sensor.mjs", "extension/import-fresh.mjs", "extension/stub.ts.tpl", "src/launch.mjs"];

export function sameSensor(rootA, rootB) {
	return SENSOR_FILES.every((file) => {
		const a = readTextSafe(path.join(rootA, file));
		return a !== undefined && a === readTextSafe(path.join(rootB, file));
	});
}

/** Same rendering as bootstrap/boot.mjs: forward slashes, three tokens. */
export function renderStub(template, { version, root }) {
	const slashed = root.replace(/\\/g, "/");
	const values = { __VERSION__: version, __FALLBACK_ROOT__: slashed, __SENSOR_PATH__: `${slashed}/extension/sensor.mjs` };
	return template.replace(/__(?:VERSION|FALLBACK_ROOT|SENSOR_PATH)__/g, (token) => values[token]);
}

/** The runtime the stub should load: app/current.json when it names one, else this repo. */
export function runtimeTarget(paths) {
	const current = readJsonSafe(paths.health.currentFile);
	return typeof current?.version === "string" && typeof current.root === "string" ? { version: current.version, root: current.root } : { version: VERSION, root: paths.repoRoot };
}

/** Stub text for `target`, rendered from its own template (this repo's when the target has none). */
export function stubContent(paths, target = runtimeTarget(paths)) {
	const template = readTextSafe(path.join(target.root, "extension", "stub.ts.tpl")) ?? fs.readFileSync(path.join(paths.repoRoot, "extension", "stub.ts.tpl"), "utf8");
	return renderStub(template, target);
}

/**
 * Whether the installed stub loads the runtime's sensor: an exact render, or an older render whose sensor files are
 * identical (boot keeps such a stub so open sessions are not reloaded; see writeStub in bootstrap/boot.mjs).
 */
export function stubCurrent(paths, text, target = runtimeTarget(paths)) {
	if (text === stubContent(paths, target)) return true;
	const loaded = /const FALLBACK_ROOT = "([^"]*)";/.exec(text ?? "")?.[1];
	return Boolean(loaded) && sameSensor(loaded, target.root);
}

/** The logon launcher always starts the bootstrap, which picks the runtime from app/current.json. */
export function launcherContent(paths, execPath) {
	return [`' omo-health hidden launcher (generated by \`omo-health install\`)`, `Set sh = CreateObject("WScript.Shell")`, `sh.Run """${execPath}"" ${DAEMON_NODE_ARGS.join(" ")} ""${paths.health.bootFile}"" daemon", 0, False`, ""].join("\r\n");
}

export function runCommandValue(paths) {
	return `wscript.exe "${path.join(paths.healthHome, "launch-hidden.vbs")}"`;
}

export function readRunValue(regRunner, env = process.env) {
	const valueName = runValueName(env);
	const result = regRunner(["query", RUN_KEY, "/v", valueName]);
	if (result.status !== 0) return undefined;
	const line = result.stdout.split(/\r?\n/).find((l) => l.includes(valueName) && l.includes("REG_"));
	if (!line) return undefined;
	return line.replace(/^\s*\S+\s+REG_\w+\s+/, "").trim();
}

/** `taskkill /F`; the caller has already verified the pid is the lock-holding daemon. */
export function taskkillDaemon(pid) {
	const result = spawnSync("taskkill.exe", ["/F", "/PID", String(pid)], { windowsHide: true });
	return result.status === 0 ? `stopped:${pid}` : `stop-failed:${pid}`;
}

/** G09: a deliberate stop is recorded before the kill, so the bootstrap never counts it as an unclean death. */
export function markDaemonStopped(paths, exitReason, now = Date.now()) {
	const hb = readJsonSafe(paths.health.daemonJson) ?? {};
	atomicWriteJson(paths.health.daemonJson, { ...hb, stoppedMs: now, exitReason });
}

function writeIfChanged(file, text) {
	if (readTextSafe(file) === text) return "unchanged";
	atomicWriteFile(file, text);
	return "written";
}

/** `git` / `tar` through spawnSync; stdout is a Buffer so a tar stream survives. */
function defaultRun(command, args, options = {}) {
	const result = spawnSync(command, args, { windowsHide: true, maxBuffer: 1 << 30, ...options });
	return { status: result.error ? null : result.status, stdout: result.stdout ?? Buffer.alloc(0), stderr: result.error?.message ?? String(result.stderr ?? "") };
}

/**
 * The commit a pinned install runs: HEAD of this checkout, which must be committed-clean for tracked files (the
 * install runs exactly what HEAD holds, so an uncommitted edit would silently not be part of it).
 */
function readHead(repoRoot, run) {
	const text = (result) => result.stdout.toString("utf8").trim();
	const head = run("git", ["rev-parse", "HEAD"], { cwd: repoRoot });
	if (head.status !== 0) throw new Error(`${repoRoot} is not a git checkout (${text(head) || head.stderr.trim()}); a pinned install copies HEAD, use \`install --dev\` to run a folder in place`);
	const dirty = run("git", ["status", "--porcelain", "--untracked-files=no"], { cwd: repoRoot });
	if (dirty.status !== 0) throw new Error(`git status failed in ${repoRoot}: ${dirty.stderr.trim()}`);
	if (text(dirty)) throw new Error(`commit first: tracked files have uncommitted changes in ${repoRoot}, and a pinned install copies HEAD:\n${text(dirty)}`);
	const manifest = run("git", ["show", "HEAD:package.json"], { cwd: repoRoot });
	const version = manifest.status === 0 ? JSON.parse(manifest.stdout.toString("utf8")).version : undefined;
	if (typeof version !== "string") throw new Error(`HEAD of ${repoRoot} has no package.json version`);
	const sha = text(head);
	return { version, sha, shortSha: sha.slice(0, 7) };
}

function readPackageHead(repoRoot, run) {
	const text = (result) => result.stdout.toString("utf8").trim();
	const head = run("git", ["rev-parse", "HEAD"], { cwd: repoRoot });
	if (head.status !== 0) throw new Error(`${repoRoot} is not a git checkout (${text(head) || head.stderr.trim()})`);
	const dirty = run("git", ["status", "--porcelain", "--untracked-files=no"], { cwd: repoRoot });
	if (dirty.status !== 0) throw new Error(`git status failed in ${repoRoot}: ${dirty.stderr.trim()}`);
	const manifest = run("git", ["show", `${text(head)}:package.json`], { cwd: repoRoot });
	const version = manifest.status === 0 ? JSON.parse(manifest.stdout.toString("utf8")).version : undefined;
	if (typeof version !== "string") throw new Error(`HEAD of ${repoRoot} has no package.json version`);
	return { version, sha: text(head), shortSha: text(head).slice(0, 7), dirty: Boolean(text(dirty)) };
}

function acquireSetupLock(file, now) {
	ensureDir(path.dirname(file));
	for (let attempt = 0; attempt < 2; attempt++) {
		try {
			const fd = fs.openSync(file, "wx");
			fs.writeFileSync(fd, JSON.stringify({ pid: process.pid, startedMs: now() }));
			return () => { fs.closeSync(fd); removeSafe(file); };
		} catch (error) {
			if (error.code !== "EEXIST") throw error;
			const holder = readJsonSafe(file);
			const alive = holder?.pid > 0 && (() => { try { process.kill(holder.pid, 0); return true; } catch (e) { return e.code === "EPERM"; } })();
			if (alive && now() - (holder.startedMs ?? now()) <= 10 * 60_000) return undefined;
			removeSafe(file);
		}
	}
	return undefined;
}

/** `git archive HEAD` extracted into <root>.staging, then renamed; an existing root is kept as is. */
function archiveHead(repoRoot, root, run, sha = "HEAD") {
	if (fs.existsSync(path.join(root, "bin", "omo-health.mjs"))) return "kept";
	const staging = `${root}.staging`;
	removeSafe(staging);
	removeSafe(root);
	ensureDir(staging);
	const archive = run("git", ["archive", "--format=tar", sha], { cwd: repoRoot });
	if (archive.status !== 0) {
		removeSafe(staging);
		throw new Error(`git archive HEAD failed: ${archive.stderr.trim()}`);
	}
	// The tar stream goes through stdin: no drive-letter path for a GNU tar to read as host:path.
	const untar = run("tar", ["-xf", "-"], { cwd: staging, input: archive.stdout });
	if (untar.status !== 0) {
		removeSafe(staging);
		throw new Error(`tar could not extract the archive: ${untar.stderr.trim()}`);
	}
	fs.renameSync(staging, root);
	return "written";
}

/**
 * Pinned-install cleanup of what the self-care and release pipeline left (plan Q3). Reports from care/deaths and
 * care/intake move to deaths/ and intake/ first; only after that do care/, the bare repo, the previous boot, staged
 * and pending-rollback files and every release other than `keepRoot` go. Every removal is a line in logs/install.log.
 * decisions, reports, snapshots, alignment, receipts, inbox, baseline, state, config and lkg/ are never touched.
 */
function cleanupLegacy({ paths, keepRoot, now }) {
	const logFile = path.join(paths.health.logsDir, "install.log");
	const log = (event, detail) => {
		ensureDir(paths.health.logsDir);
		fs.appendFileSync(logFile, `${new Date(now()).toISOString()} ${event} ${detail}\n`);
	};
	const result = { migrated: { deaths: 0, intake: 0 }, removed: [], failed: [] };
	const careDir = paths.health.legacyCareDir;
	let migrated = true;
	if (fs.existsSync(careDir)) {
		try {
			const legacyDeaths = path.join(careDir, "deaths");
			for (const name of fs.existsSync(legacyDeaths) ? fs.readdirSync(legacyDeaths) : []) {
				const target = path.join(paths.health.deathsDir, name);
				if (fs.existsSync(target)) continue;
				ensureDir(paths.health.deathsDir);
				fs.renameSync(path.join(legacyDeaths, name), target);
				result.migrated.deaths++;
				log("migrated", `${path.join(legacyDeaths, name)} -> ${target}`);
			}
			result.migrated.intake = importLegacyIntake(paths, path.join(careDir, "intake"));
			if (result.migrated.intake) log("migrated", `${result.migrated.intake} intake file(s) from ${path.join(careDir, "intake")} -> ${paths.health.intakeDir}`);
		} catch (error) {
			// Nothing is deleted from care/ when its reports could not be moved out.
			migrated = false;
			result.failed.push(careDir);
			log("migrate-failed", `${careDir}: ${error.message}`);
		}
	}
	const app = paths.health.appDir;
	const listApp = (dir, keep = () => false) => (fs.existsSync(dir) ? fs.readdirSync(dir).filter((name) => !keep(name)) : []);
	const targets = [
		...(migrated ? [careDir] : []),
		path.join(app, "repo.git"),
		...listApp(app, (name) => !/^(staged.*\.json|pending-rollback.*|boot\.prev\.mjs)$/.test(name)).map((name) => path.join(app, name)),
		...listApp(paths.health.releasesDir, (name) => pathKey(path.join(paths.health.releasesDir, name)) === pathKey(keepRoot)).map((name) => path.join(paths.health.releasesDir, name)),
	];
	for (const target of targets) {
		if (!fs.existsSync(target)) continue;
		try {
			fs.rmSync(target, { recursive: true, force: true, maxRetries: 3, retryDelay: 100 });
			result.removed.push(target);
			log("removed", target);
		} catch (error) {
			result.failed.push(target);
			log("remove-failed", `${target}: ${error.message}`);
		}
	}
	return result;
}

/**
 * Idempotent install. Pinned (default): `git archive HEAD` of this checkout into app/releases/<version>-<shortsha>,
 * app/current.json {channel:"pinned"} at it; refused while a tracked file is uncommitted, before anything changes.
 * `dev`: app/current.json points at this checkout. Both copy the bootstrap to app/boot.mjs, write the stub and the
 * hidden launcher (only when their content differs, so sessions do not hot-reload for nothing), set the HKCU Run
 * value, and replace a daemon running another root. A pinned install then cleans up the legacy release/care data.
 */
export async function install({ paths, dev = false, fromPackage = false, execPath = process.execPath, regRunner = defaultRegRunner, startDaemon, killDaemon = taskkillDaemon, run = defaultRun, now = Date.now }) {
	if (fromPackage) {
		const release = readPackageHead(paths.repoRoot, run);
		const releaseRoot = path.join(paths.health.releasesDir, `${release.version}-${release.shortSha}`);
		const releaseLock = path.join(paths.health.appDir, "setup.lock");
		ensureDir(paths.health.appDir);
		const unlock = acquireSetupLock(releaseLock, now);
		if (!unlock) return { skipped: "locked" };
		const report = { channel: "package", version: release.version, sha: release.sha, dirty: release.dirty, release: "written", current: "unchanged", boot: "unchanged", stub: "absent", launcher: "unchanged", runKey: "unchanged", daemon: "running" };
		const logFile = path.join(paths.health.logsDir, "install.log");
		const log = (event, detail) => { ensureDir(paths.health.logsDir); fs.appendFileSync(logFile, `${new Date(now()).toISOString()} ${event} ${detail}\n`); };
		try {
			const checkArchive = run("git", ["archive", "--format=tar", release.sha], { cwd: paths.repoRoot });
			if (checkArchive.status !== 0) throw new Error(`git archive ${release.sha} failed: ${checkArchive.stderr.trim()}`);
			const prior = readJsonSafe(paths.health.currentFile);
			if (prior?.channel === "dev") return { skipped: "dev" };
			const sameRelease = prior?.channel === "package" && prior.sha === release.sha && pathKey(prior.source) === pathKey(paths.repoRoot) && fs.existsSync(path.join(prior.root ?? "", "bin", "omo-health.mjs"));
			const dirs = [paths.healthHome, paths.health.appDir, paths.health.releasesDir, paths.health.logsDir, ...Object.entries(paths.health).filter(([k]) => k.endsWith("Dir") && !pathKey(paths.health[k]).startsWith(pathKey(paths.health.legacyCareDir))).map(([, v]) => v)];
			for (const dir of dirs) ensureDir(dir);
			const stubDir = paths.extensionsDir;
			ensureDir(stubDir);
			if (sameRelease) report.release = "current";
			else {
				report.release = archiveHead(paths.repoRoot, releaseRoot, run, release.sha);
				const current = { channel: "package", source: path.resolve(paths.repoRoot), version: release.version, sha: release.sha, root: releaseRoot, installedMs: now() };
				report.current = writeIfChanged(paths.health.currentFile, `${JSON.stringify(current, null, 2)}\n`);
				cleanupLegacy({ paths, keepRoot: releaseRoot, now });
			}
			const stubFile = path.join(stubDir, STUB_NAME);
			if (fs.existsSync(stubFile)) { fs.rmSync(stubFile, { force: true }); report.stub = "removed"; }
			const boot = readTextSafe(path.join(releaseRoot, "bootstrap", "boot.mjs"));
			if (boot === undefined) throw new Error(`${releaseRoot} has no bootstrap/boot.mjs`);
			report.boot = writeIfChanged(paths.health.bootFile, boot);
			report.launcher = writeIfChanged(path.join(paths.healthHome, "launch-hidden.vbs"), launcherContent(paths, execPath));
			const wanted = runCommandValue(paths), valueName = runValueName();
			if (readRunValue(regRunner) !== wanted) {
				const result = regRunner(["add", RUN_KEY, "/v", valueName, "/t", "REG_SZ", "/d", wanted, "/f"]);
				report.runKey = result.status === 0 ? "written" : `failed:${result.stderr.trim()}`;
			}
			removeSafe(paths.health.stoppedFile);
			const state = daemonState(paths);
			let start = !state.running;
			if (state.running && (typeof state.heartbeat?.root !== "string" || pathKey(state.heartbeat.root) !== pathKey(releaseRoot))) {
				markDaemonStopped(paths, "install", now());
				report.replaced = killDaemon(state.pid);
				start = true;
			}
			if (start) report.daemon = startDaemon ? `started:${await startDaemon()}` : "not-started";
			atomicWriteJson(path.join(paths.health.appDir, "setup-state.json"), { sha: release.sha, doneMs: now() });
			log("setup-complete", release.sha);
			return report;
		} catch (error) {
			ensureDir(paths.health.appDir);
			ensureDir(paths.health.logsDir);
			const state = { sha: release.sha, failedMs: now(), error: error.message };
			atomicWriteJson(path.join(paths.health.appDir, "setup-state.json"), state);
			log("setup-failed", `${release.sha} ${error.message}`);
			throw error;
		} finally { unlock(); }
	}
	// Refuse before touching anything.
	const head = dev ? undefined : readHead(paths.repoRoot, run);
	const report = { channel: dev ? "dev" : "pinned", version: undefined, current: "unchanged", boot: "unchanged", stub: "unchanged", launcher: "unchanged", runKey: "unchanged", daemon: "running" };
	const legacyCare = pathKey(paths.health.legacyCareDir);
	// The care folders are legacy: a fresh install does not create them (the pinned cleanup removes them).
	for (const [key, dir] of Object.entries(paths.health)) if (key.endsWith("Dir") && !pathKey(dir).startsWith(legacyCare)) ensureDir(dir);
	ensureDir(paths.extensionsDir);

	const currentBefore = readTextSafe(paths.health.currentFile);
	let target;
	let current;
	if (head) {
		target = { version: head.version, root: path.join(paths.health.releasesDir, `${head.version}-${head.shortSha}`) };
		report.sha = head.sha;
		report.archive = archiveHead(paths.repoRoot, target.root, run);
		const prior = readJsonSafe(paths.health.currentFile);
		const same = prior?.channel === "pinned" && prior.sha === head.sha && prior.version === head.version && typeof prior.root === "string" && pathKey(prior.root) === pathKey(target.root);
		current = { channel: "pinned", version: target.version, sha: head.sha, root: target.root, installedMs: same && Number.isFinite(prior.installedMs) ? prior.installedMs : now() };
	} else {
		target = { version: VERSION, root: paths.repoRoot };
		current = { channel: "dev", version: target.version, root: target.root, previous: null, lkg: { ...target }, bad: [] };
	}
	report.version = target.version;
	const currentText = `${JSON.stringify(current, null, 2)}\n`;
	writeIfChanged(paths.health.currentFile, currentText);
	report.current = currentBefore === currentText ? "unchanged" : "written";

	const boot = readTextSafe(path.join(target.root, "bootstrap", "boot.mjs"));
	if (boot === undefined) throw new Error(`${target.root} has no bootstrap/boot.mjs`);
	report.boot = writeIfChanged(paths.health.bootFile, boot);
	report.stub = writeIfChanged(path.join(paths.extensionsDir, STUB_NAME), stubContent(paths, target));
	report.launcher = writeIfChanged(path.join(paths.healthHome, "launch-hidden.vbs"), launcherContent(paths, execPath));

	const wanted = runCommandValue(paths), valueName = runValueName();
	if (readRunValue(regRunner) !== wanted) {
		const result = regRunner(["add", RUN_KEY, "/v", valueName, "/t", "REG_SZ", "/d", wanted, "/f"]);
		report.runKey = result.status === 0 ? "written" : `failed:${result.stderr.trim()}`;
	}

	removeSafe(paths.health.stoppedFile);
	const state = daemonState(paths);
	let start = !state.running;
	// daemonState.running is the lockHolderLive check: the pid holds the lock and heartbeats as our daemon.
	const runningRoot = state.heartbeat?.root;
	if (state.running && (typeof runningRoot !== "string" || pathKey(runningRoot) !== pathKey(target.root))) {
		markDaemonStopped(paths, "install", now());
		report.replaced = killDaemon(state.pid);
		start = true;
	}
	// After the old daemon is gone: its release root can then be deleted.
	if (head) report.cleanup = cleanupLegacy({ paths, keepRoot: target.root, now });
	if (start) report.daemon = startDaemon ? `started:${await startDaemon()}` : "not-started";
	return report;
}

/** Remove stub + Run value, stop the daemon; --purge also deletes healthHome. */
function pidAlive(pid) {
	try {
		process.kill(pid, 0);
		return true;
	} catch (error) {
		return error.code === "EPERM";
	}
}

function sleepSync(ms) {
	Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, ms);
}

export function uninstall({ paths, regRunner = defaultRegRunner, stopDaemon, purge = false, now = Date.now, alive = pidAlive, sleep = sleepSync }) {
	const report = { stub: "absent", runKey: "absent", launcher: "absent", daemon: "not-running", purge: false };
	const current = readJsonSafe(paths.health.currentFile);
	const stubFile = path.join(paths.extensionsDir, STUB_NAME);
	if (fs.existsSync(stubFile)) {
		fs.rmSync(stubFile, { force: true });
		report.stub = "removed";
	}
	if (readRunValue(regRunner) !== undefined) {
		const result = regRunner(["delete", RUN_KEY, "/v", runValueName(), "/f"]);
		report.runKey = result.status === 0 ? "removed" : `failed:${result.stderr.trim()}`;
	}
	const launcher = path.join(paths.healthHome, "launch-hidden.vbs");
	if (fs.existsSync(launcher)) {
		fs.rmSync(launcher, { force: true });
		report.launcher = "removed";
	}
	ensureDir(paths.healthHome);
	fs.writeFileSync(paths.health.stoppedFile, new Date().toISOString());
	const state = daemonState(paths);
	if (state.running) {
		if (stopDaemon) markDaemonStopped(paths, "uninstall", now());
		report.daemon = stopDaemon ? stopDaemon(state.pid) : "running";
	}
	if (purge) {
		// The killed daemon and its process worker still hold the DB and the worker exe until they are gone.
		const holders = [state.running ? state.pid : undefined, state.heartbeat?.workerPid].filter((pid) => Number.isInteger(pid) && pid > 0);
		for (let waited = 0; waited < 20_000 && holders.some((pid) => alive(pid)); waited += 250) sleep(250);
		// Windows cannot delete a folder that is this process's cwd (`/health uninstall --purge` runs with cwd = healthHome),
		// and the daemon just killed above (and its process worker) can hold the DB and worker exe for a moment.
		if (pathKey(process.cwd()).startsWith(pathKey(paths.healthHome))) process.chdir(path.dirname(paths.healthHome));
		try {
			fs.rmSync(paths.healthHome, { recursive: true, force: true, maxRetries: 20, retryDelay: 250 });
			report.purge = true;
		} catch (error) {
			report.purge = `failed:${error.code ?? error.message}`;
		}
		if (current?.channel === "package") {
			ensureDir(paths.healthHome);
			fs.writeFileSync(paths.health.stoppedFile, new Date(now()).toISOString());
		}
	}
	return report;
}
